/** Slug de una categoría para claves con punto (`expenses_by_category.<slug>`). */
export function categorySlug(name: string): string {
  return (
    name
      .normalize('NFD')
      .replace(/[̀-ͯ]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '') || 'sin_nombre'
  );
}
